// jaw: 'upper' | 'lower' — необходимо явно, т.к. одна и та же форма (molar/premolar)
// использует разные схемы смещения корней в зависимости от челюсти.
export function rootTips(o, jaw) {
    const { md, bl, roots, position } = o;
    if (roots === 3) return ROOT_OFFSETS.upperMolar3(md, bl);
    if (roots === 2) {
        if (jaw === 'lower') return ROOT_OFFSETS.lowerMolar2(md, bl);
        // Верхний 2-корневой: премоляр (позиция 4) — нёбный/щёчный корень вдоль bl;
        // "восьмёрка" (позиция 8) — корни смещены по диагонали md/bl.
        return position === 4 ? ROOT_OFFSETS.upperPremolar2(md, bl) : ROOT_OFFSETS.upperEight2(md, bl);
    }
    return null;
}

export function surfacesFor(o) {
    return o.position <= 3 ? ['M', 'D', 'I', 'B', 'L'] : ['M', 'D', 'O', 'B', 'L'];
}
