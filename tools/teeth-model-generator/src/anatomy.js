// Смещения корней для многокорневых зубов, доли md/bl (+Z вестибулярно). §4.
export const ROOT_OFFSETS = {
    upperMolar3: (md, bl) => [[.30 * md, .30 * bl], [-.30 * md, .30 * bl], [0, -.36 * bl]],
    upperPremolar2: (md, bl) => [[0, .30 * bl], [0, -.30 * bl]],
    upperEight2: (md, bl) => [[.20 * md, .16 * bl], [-.20 * md, -.16 * bl]],
    lowerMolar2: (md, bl) => [[.30 * md, 0], [-.30 * md, 0]]
};

